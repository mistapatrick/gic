import "server-only";
import { parseFoodSecurityRecords, type FoodSecurityObservation } from "@/lib/domains/food-security/ingest-logic";
import { getSupabaseAdminClient } from "@/lib/supabase/admin";
import { GIC_OUTBOUND_HEADERS } from "@/lib/ingestion/outbound-headers";

/**
 * HDX HAPI's network/auth side — the direct parallel of
 * production-conditions/bulk-backfill.ts and
 * commodity-prices/fewsnet-backfill.ts, kept separate from
 * food-security/ingest-logic.ts's pure parsing.
 *
 * Auth flow confirmed from HDX's own docs (docs.humdata.org/build/hdx-apis
 * /hapi/how-to-query-hapi, /api-reference/generate-app-identifier): every
 * request needs an "app identifier" — NOT a secret, just a base64 encoding
 * of an application name + contact email, generated by a public GET
 * endpoint and passed back on every later request. Rather than guess the
 * exact encoding (the docs say "base64" but not the precise delimiter
 * format), this calls the real encode endpoint once per ingest run and
 * uses whatever it returns — avoiding a repeat of the FAOSTAT lesson
 * (never reimplement a third-party platform's own algorithm from a partial
 * description when the platform will just tell you the answer directly).
 *
 * Endpoint path (api/v2/food-security-nutrition-poverty/food-security) is
 * confirmed from HDX HAPI's own published OpenAPI spec excerpt
 * (docs.humdata.org/build/hdx-apis/hapi/api-reference/food-security-nutrition-and-poverty).
 * Pagination (limit/offset, looping until a page returns fewer rows than
 * the limit requested) follows HDX's own documented guidance
 * (docs.humdata.org/build/hdx-apis/hapi/troubleshooting-and-error-handling:
 * "HAPI returns at most 10,000 records per call") — Nigeria's own food
 * security series is expected to be far smaller than that per page, but
 * the loop is unconditional rather than assuming one page is always
 * enough.
 */

const HAPI_BASE = "https://hapi.humdata.org";
const APPLICATION_NAME = "Growthly Intelligence Centre";
const APPLICATION_EMAIL = "yusuf@growthlysolutions.com";
const PAGE_LIMIT = 1000;

async function fetchJson(url: string, timeoutMs: number): Promise<unknown> {
  const res = await fetch(url, {
    cache: "no-store",
    signal: AbortSignal.timeout(timeoutMs),
    headers: { ...GIC_OUTBOUND_HEADERS, Accept: "application/json" },
  });
  if (!res.ok) {
    throw new Error(`Request to ${url} failed: HTTP ${res.status}`);
  }
  const contentType = res.headers.get("content-type") ?? "";
  const text = await res.text();
  const looksLikeHtml =
    contentType.includes("html") || text.trim().slice(0, 200).toLowerCase().includes("<html");
  if (looksLikeHtml) {
    throw new Error(`Request to ${url} returned an HTML page instead of JSON — refusing to parse it as data.`);
  }
  try {
    return JSON.parse(text);
  } catch {
    throw new Error(`Request to ${url} did not return valid JSON.`);
  }
}

async function getAppIdentifier(): Promise<string> {
  const url = `${HAPI_BASE}/api/v2/encode_app_identifier?application=${encodeURIComponent(
    APPLICATION_NAME
  )}&email=${encodeURIComponent(APPLICATION_EMAIL)}`;
  const json = await fetchJson(url, 15_000);
  if (
    typeof json !== "object" ||
    json === null ||
    typeof (json as { encoded_app_identifier?: unknown }).encoded_app_identifier !== "string"
  ) {
    throw new Error("HDX HAPI encode_app_identifier response has no encoded_app_identifier string field.");
  }
  return (json as { encoded_app_identifier: string }).encoded_app_identifier;
}

/**
 * The live envelope shape isn't independently confirmed from this build
 * environment (network allowlist blocks hapi.humdata.org) — handles both
 * a flat top-level array and the common REST convention of an object with
 * a "data" array, same defensive spirit as fewsnet-backfill.ts's
 * extractRecords().
 */
function extractRecords(responseJson: unknown): Array<Record<string, unknown>> {
  if (Array.isArray(responseJson)) {
    return responseJson as Array<Record<string, unknown>>;
  }
  if (typeof responseJson === "object" && responseJson !== null) {
    const obj = responseJson as Record<string, unknown>;
    if (Array.isArray(obj.data)) return obj.data as Array<Record<string, unknown>>;
  }
  throw new Error(
    "HDX HAPI food_security response is neither a flat array nor an object with a data array — " +
      "its shape may differ from what this parser expects."
  );
}

async function fetchAllPages(appIdentifier: string): Promise<Array<Record<string, unknown>>> {
  const all: Array<Record<string, unknown>> = [];
  let offset = 0;

  // Unconditional pagination loop per HDX's own documented guidance (see
  // this file's header comment) — stops once a page returns fewer rows
  // than PAGE_LIMIT, which also correctly terminates a single-page result.
  // A hard cap keeps a misbehaving endpoint from looping forever.
  for (let page = 0; page < 50; page++) {
    const url =
      `${HAPI_BASE}/api/v2/food-security-nutrition-poverty/food-security` +
      `?location_code=NGA&output_format=json&limit=${PAGE_LIMIT}&offset=${offset}` +
      `&app_identifier=${encodeURIComponent(appIdentifier)}`;
    const json = await fetchJson(url, 30_000);
    const records = extractRecords(json);
    all.push(...records);
    if (records.length < PAGE_LIMIT) break;
    offset += PAGE_LIMIT;
  }

  return all;
}

export async function fetchFoodSecurityBackfillChunk(): Promise<Array<Record<string, unknown>>> {
  const appIdentifier = await getAppIdentifier();
  return fetchAllPages(appIdentifier);
}

export function parseFoodSecurityBackfillChunk(
  records: Array<Record<string, unknown>>
): FoodSecurityObservation[] {
  return parseFoodSecurityRecords(records);
}

export async function writeFoodSecurityBackfillChunk(records: Array<Record<string, unknown>>): Promise<number> {
  const rows = parseFoodSecurityBackfillChunk(records);
  if (rows.length === 0) return 0;

  const admin = getSupabaseAdminClient();
  const { error } = await admin.from("food_security_observations").upsert(
    rows.map((r) => ({
      location_code: r.locationCode,
      location_name: r.locationName,
      admin_level: r.adminLevel,
      // Coalesced to '' rather than left null: Postgres treats two NULLs
      // as distinct for uniqueness purposes, which would silently break
      // idempotent upsert for national-level rows (no admin1/admin2) by
      // inserting a fresh duplicate on every run instead of updating the
      // existing one. See migration 0006's column definitions.
      admin1_code: r.admin1Code || "",
      admin1_name: r.admin1Name || "",
      admin2_code: r.admin2Code || "",
      admin2_name: r.admin2Name || "",
      ipc_phase: r.ipcPhase,
      ipc_type: r.ipcType,
      population_in_phase: r.populationInPhase,
      population_fraction_in_phase: r.populationFractionInPhase,
      reference_period_start: r.referencePeriodStart,
      reference_period_end: r.referencePeriodEnd,
      resource_hdx_id: r.resourceHdxId,
    })),
    {
      onConflict:
        "location_code,admin1_code,admin2_code,ipc_phase,ipc_type,reference_period_start",
    }
  );
  if (error) throw new Error(`food_security_observations upsert failed: ${error.message}`);

  return rows.length;
}
