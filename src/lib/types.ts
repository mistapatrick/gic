export const GEO_ZONES = [
  "South-East",
  "South-South",
  "North-West",
  "North-East",
  "North-Central",
  "South-West",
] as const;

export type GeoZone = (typeof GEO_ZONES)[number];

export interface HourlyPoint {
  obs_hour: number;
  label: string;
  precip_mm: number;
  cum_precip_mm: number;
  rel_humidity_pct: number;
  wind_speed_kmh: number;
  temp_2m_c: number;
  avg_temp_c: number;
  max_temp_c: number;
  min_temp_c: number;
  sunshine_hrs: number;
  cum_sunshine_hrs: number;
}

export type RiskFlagSeverity = "info" | "watch" | "alert";

/**
 * A deterministic, rule-based agronomic risk flag — computed in code from
 * the night's own observed telemetry, not generated by the AI brief. This
 * matters for a B2B/bid/program-briefing use case: a flag Growthly staff
 * cite in a client report or funder bid has to be exact and reproducible,
 * not a plausible-sounding AI sentence. See computeRiskFlags() in
 * ingest-logic.ts for the threshold definitions.
 */
export interface RiskFlag {
  code: string;
  label: string;
  severity: RiskFlagSeverity;
  detail: string;
}

export interface ClusterMetrics {
  cluster_id: number;
  slug: string;
  state_label: string;
  cluster_name: string;
  geo_zone: GeoZone;
  latitude: number;
  longitude: number;
  total_precip_mm: number;
  avg_humidity_pct: number;
  avg_wind_kmh: number;
  avg_temp_c: number;
  max_temp_c: number;
  min_temp_c: number;
  total_sunshine_hrs: number;
  hourly: HourlyPoint[];
  risk_flags: RiskFlag[];
}

export interface RegionalInsight {
  geo_zone: GeoZone;
  headline: string;
  observed_anomaly: string;
  agronomic_implication: string;
}

export interface DailyObservedReport {
  id?: number;
  obs_date: string;
  cutoff_hour_wat: number;
  national_summary: string;
  regional_insights: RegionalInsight[];
  cluster_metrics: ClusterMetrics[];
  generated_at?: string;
}
